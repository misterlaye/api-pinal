package com.dairy.apipinal.finance;

import com.dairy.apipinal.finance.application.RentabiliteService;
import com.dairy.apipinal.finance.application.CalculateRentabilite;
import com.dairy.apipinal.finance.domain.CalculRentabilite;
import com.dairy.apipinal.finance.infrastructure.persistence.CalculRentabiliteRepository;
import com.dairy.apipinal.shared.security.TenantContext;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.context.ActiveProfiles;

import java.time.LocalDate;
import java.time.YearMonth;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.when;
import java.math.RoundingMode;

@SpringBootTest
@ActiveProfiles("test") // Ensures we use test DB
class SnapshotReconstructibilityIT {

    @Autowired
    private RentabiliteService rentabiliteService;

    @Autowired
    private CalculRentabiliteRepository snapshotRepository;

    @MockitoBean
    private TenantContext tenantContext;

    @Test
    void historicalSnapshotsShouldBeExactlyReconstructibleFromSourceData() {
        UUID tenantId = UUID.fromString("b0000000-0000-0000-0000-000000000001");
        UUID exploitationId = UUID.fromString("d2c88f9a-1111-4b11-1111-d11111111111");
        when(tenantContext.currentTenantId()).thenReturn(tenantId);

        YearMonth currentMonth = YearMonth.now();

        // Validate Mois-1
        YearMonth mois1 = currentMonth.minusMonths(1);
        validateSnapshotReconstructibility(mois1, tenantId);

        // Validate Mois-2
        YearMonth mois2 = currentMonth.minusMonths(2);
        validateSnapshotReconstructibility(mois2, tenantId);
    }

    private void validateSnapshotReconstructibility(YearMonth targetMonth, UUID tenantId) {
        LocalDate startOfMonth = targetMonth.atDay(1);
        LocalDate endOfMonth = targetMonth.atEndOfMonth();

        // 1. Calculate Dynamically from raw source data (traites, charges, rations)
        CalculRentabilite liveCalcul = rentabiliteService.calculateLive(
                new CalculateRentabilite(startOfMonth, endOfMonth)
        );

        // 2. Fetch the snapshot generated by V23
        Optional<CalculRentabilite> optionalSnapshot = snapshotRepository.findAllByTenantIdOrderByDateCalculDesc(tenantId)
                .stream()
                .filter(s -> YearMonth.from(s.getPeriodeDebut()).equals(targetMonth))
                .findFirst();

        assertThat(optionalSnapshot).isPresent();
        CalculRentabilite snapshot = optionalSnapshot.get();

        // 3. Assert mathematical equality (rounded to 2 decimals)
        assertThat(liveCalcul.getVolumeLait().setScale(2, RoundingMode.HALF_UP))
                .isEqualByComparingTo(snapshot.getVolumeLait().setScale(2, RoundingMode.HALF_UP));
                
        assertThat(liveCalcul.getChiffreAffaires().setScale(2, RoundingMode.HALF_UP))
                .isEqualByComparingTo(snapshot.getChiffreAffaires().setScale(2, RoundingMode.HALF_UP));
                
        assertThat(liveCalcul.getCoutAlimentation().setScale(2, RoundingMode.HALF_UP))
                .isEqualByComparingTo(snapshot.getCoutAlimentation().setScale(2, RoundingMode.HALF_UP));
                
        assertThat(liveCalcul.getAutresCharges().setScale(2, RoundingMode.HALF_UP))
                .isEqualByComparingTo(snapshot.getAutresCharges().setScale(2, RoundingMode.HALF_UP));
                
        assertThat(liveCalcul.getMarge().setScale(2, RoundingMode.HALF_UP))
                .isEqualByComparingTo(snapshot.getMarge().setScale(2, RoundingMode.HALF_UP));
    }
}
