-- Snapshot de septembre calcule depuis les traites, prix, rations et charges.
WITH jours_periode AS (
    SELECT g::date AS jour
    FROM generate_series(DATE '2026-09-01', DATE '2026-09-30', INTERVAL '1 day') AS g
),
production AS (
    SELECT
        sum(t.quantite_litres) AS volume_lait,
        sum(t.quantite_litres * p.prix_par_litre) AS chiffre_affaires
    FROM traite t
    JOIN prix_vente_lait p
      ON p.tenant_id = t.tenant_id
     AND t.date_heure::date >= p.date_debut
     AND (p.date_fin IS NULL OR t.date_heure::date <= p.date_fin)
    WHERE t.tenant_id = 'b0000000-0000-0000-0000-000000000001'
      AND t.exploitation_id = 'b0000000-0000-0000-0000-000000000003'
      AND t.date_heure::date BETWEEN DATE '2026-09-01' AND DATE '2026-09-30'
),
alimentation AS (
    SELECT sum(lr.quantite * pa.prix_unitaire) AS cout_alimentation
    FROM jours_periode j
    JOIN ration r
      ON r.tenant_id = 'b0000000-0000-0000-0000-000000000001'
     AND r.exploitation_id = 'b0000000-0000-0000-0000-000000000003'
     AND r.statut IN ('ACTIVE', 'TERMINEE')
     AND r.date_debut <= j.jour
     AND (r.date_fin IS NULL OR r.date_fin >= j.jour)
    JOIN ligne_ration lr ON lr.ration_id = r.id
    JOIN prix_aliment pa
      ON pa.aliment_id = lr.aliment_id
     AND pa.date_debut <= j.jour
     AND (pa.date_fin IS NULL OR pa.date_fin >= j.jour)
),
charges AS (
    SELECT sum(c.montant) AS autres_charges
    FROM charge_exploitation c
    WHERE c.tenant_id = 'b0000000-0000-0000-0000-000000000001'
      AND c.exploitation_id = 'b0000000-0000-0000-0000-000000000003'
      AND c.categorie <> 'ALIMENTATION'
      AND c.date BETWEEN DATE '2026-09-01' AND DATE '2026-09-30'
),
valeurs AS (
    SELECT
        round(p.volume_lait, 4) AS volume_lait,
        round(p.chiffre_affaires, 4) AS chiffre_affaires,
        round(a.cout_alimentation, 4) AS cout_alimentation,
        round(c.autres_charges, 4) AS autres_charges
    FROM production p
    CROSS JOIN alimentation a
    CROSS JOIN charges c
)
